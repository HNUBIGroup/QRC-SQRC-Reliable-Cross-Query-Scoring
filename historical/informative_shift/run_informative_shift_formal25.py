import importlib.util
import json
import os
import sys
from pathlib import Path
from typing import Any

os.environ["CUDA_VISIBLE_DEVICES"] = ""

import numpy as np
import pandas as pd


ROOT = Path("/home/u2508283030/ECARF_Article2_20260911/12_qrc_controlled_informative_shift_20260920")
FORMAL_MANIFEST_PATH = ROOT / "00_admin/FORMAL25_EXECUTION_MANIFEST.json"
FORMAL_MANIFEST_SHA_PATH = ROOT / "00_admin/FORMAL25_EXECUTION_MANIFEST.sha256"
SMOKE_RUNNER_PATH = ROOT / "02_code/run_informative_shift_smoke.py"
OUTPUT = ROOT / "03_outputs/formal25"
