#!/usr/bin/env python3
"""CPU-only formal 25-seed controlled informative-shift benchmark.

This runner preserves the frozen seed-0 data, residual, labels, informative
component, score construction, grid, and QC definitions. Synthetic seeds
change only the nuisance vector generated by the frozen RNG rule.
"""

