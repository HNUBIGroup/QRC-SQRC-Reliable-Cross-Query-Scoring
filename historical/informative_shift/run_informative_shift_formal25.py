def load_smoke_module() -> Any:
    spec = importlib.util.spec_from_file_location("frozen_informative_shift_smoke", SMOKE_RUNNER_PATH)
    if spec is None or spec.loader is None:
        raise RuntimeError("SMOKE_RUNNER_IMPORT_SPEC_FAIL")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def write_json(path: Path, value: Any) -> None:
    path.write_text(json.dumps(value, indent=2, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8")


def mean_std_aggregate(frame: pd.DataFrame, group_columns: list[str], value_columns: list[str]) -> pd.DataFrame:
    grouped = frame.groupby(group_columns, sort=True, dropna=False)[value_columns].agg(["mean", "std"])
    grouped.columns = [f"{column}_{stat}" for column, stat in grouped.columns]
    return grouped.reset_index()


def heatmap(frame: pd.DataFrame, value: str, betas: tuple[float, ...], gammas: tuple[float, ...]) -> pd.DataFrame:
    matrix = frame.pivot(index="gamma", columns="beta", values=value).reindex(index=gammas, columns=betas)
    matrix.index.name = "gamma"
    matrix.columns = [f"beta_{float(column):g}" for column in matrix.columns]
    return matrix.reset_index()


def fmt(value: float) -> str:
    return f"{value:.12g}"


def main() -> int:
    smoke = load_smoke_module()
    formal_manifest = json.loads(FORMAL_MANIFEST_PATH.read_text(encoding="utf-8"))
    expected_manifest_sha = FORMAL_MANIFEST_SHA_PATH.read_text(encoding="utf-8").split()[0]
    actual_manifest_sha = sha256_file(FORMAL_MANIFEST_PATH)
    if actual_manifest_sha != expected_manifest_sha:
        raise RuntimeError("FORMAL25_EXECUTION_MANIFEST_HASH_MISMATCH")

    if not formal_manifest["cpu_only"] or formal_manifest["gpu_allowed"]:
        raise RuntimeError("CPU_ONLY_PROTOCOL_MISMATCH")
    if formal_manifest["protocol_changes_allowed"] or formal_manifest["test_derived_tuning_allowed"]:
        raise RuntimeError("FORMAL25_PROTOCOL_PERMISSION_MISMATCH")
    seeds = tuple(int(value) for value in formal_manifest["synthetic_seeds"])
    betas = tuple(float(value) for value in formal_manifest["beta_grid"])
    gammas = tuple(float(value) for value in formal_manifest["gamma_grid"])
    if seeds != tuple(range(25)):
        raise RuntimeError("FORMAL25_SEED_SCOPE_MISMATCH")
    if betas != (0.0, 0.25, 0.5, 1.0, 2.0) or gammas != (0.0, 0.25, 0.5, 1.0, 2.0):
        raise RuntimeError("FROZEN_GRID_MISMATCH")
    if float(formal_manifest["alpha"]) != 1.0 or int(formal_manifest["condition_count"]) != 625:
        raise RuntimeError("FROZEN_FORMAL_SCOPE_MISMATCH")

    source_snapshot: dict[str, Any] = {}
    for name, entry in formal_manifest["source_freeze"].items():
        path = Path(entry["path"])
        actual = sha256_file(path)
        source_snapshot[name] = {
            "path": str(path),
            "expected_sha256": entry["sha256"],
            "actual_sha256": actual,
            "hash_match": actual == entry["sha256"],
        }
    if not all(entry["hash_match"] for entry in source_snapshot.values()):
        raise RuntimeError("FORMAL25_SOURCE_HASH_MISMATCH")

    smoke_manifest_path = Path(formal_manifest["source_freeze"]["smoke_manifest"]["path"])
    smoke_manifest = json.loads(smoke_manifest_path.read_text(encoding="utf-8"))
    tolerance = float(smoke_manifest["algebraic_tolerance"])
    macro_tolerance = float(smoke_manifest["macro_invariance_tolerance"])
    degenerate_threshold = float(smoke_manifest["degenerate_variance_threshold"])

    frozen_input_snapshot: dict[str, Any] = {}
    for name, entry in smoke_manifest["inputs"].items():
        path = Path(entry["path"])
        actual = sha256_file(path)
        frozen_input_snapshot[name] = {
            "path": str(path),
            "expected_sha256": entry["sha256"],
            "actual_sha256": actual,
            "hash_match": actual == entry["sha256"],
        }
    if not all(entry["hash_match"] for entry in frozen_input_snapshot.values()):
        raise RuntimeError("FROZEN_INPUT_HASH_MISMATCH")

    old_verification = json.loads(
        Path(smoke_manifest["inputs"]["old_independent_verification"]["path"]).read_text(encoding="utf-8")
    )
    if old_verification["status"] != "INDEPENDENT_VERIFICATION_PASS":
        raise RuntimeError("OLD_CONTROLLED_VERIFICATION_NOT_PASS")

    score_path = Path(smoke_manifest["inputs"]["frozen_pair_scores"]["path"])
    entity_path = Path(smoke_manifest["inputs"]["frozen_test_entities"]["path"])
    scores = pd.read_csv(
        score_path,
        sep="\t",
        usecols=["drug", "miRNA", "split", "molecular_score", "final_score"],
    )
    test_queries = set(pd.read_csv(entity_path, sep="\t").iloc[:, 0].astype(str))
    test = scores[
        scores["drug"].astype(str).isin(test_queries)
        & scores["split"].isin([smoke_manifest["positive_split"], smoke_manifest["pseudo_negative_split"]])
    ].copy()
    test["drug"] = test["drug"].astype(str)
    test["miRNA"] = test["miRNA"].astype(str)
    test = test.sort_values(["drug", "miRNA"], kind="mergesort").reset_index(drop=True)
    if len(test) != len(test_queries) * 1195:
        raise RuntimeError(f"INCOMPLETE_CANDIDATE_SET: rows={len(test)}")
    if test.duplicated(["drug", "miRNA"]).any():
        raise RuntimeError("DUPLICATE_PAIR_KEY")
    if set(test["drug"].unique()) != test_queries:
        raise RuntimeError("QUERY_ALIGNMENT_FAIL")
    candidate_counts = test.groupby("drug")["miRNA"].nunique()
    if not (candidate_counts == 1195).all():
        raise RuntimeError(f"CANDIDATE_ALIGNMENT_FAIL: {candidate_counts.to_dict()}")

    test["label"] = (test["split"] == smoke_manifest["positive_split"]).astype(np.int8)
    queries = test["drug"].to_numpy(str)
    labels = test["label"].to_numpy(np.int8)
    unique_queries = np.array(sorted(np.unique(queries)))
    base = test[smoke_manifest["base_column"]].to_numpy(np.longdouble)
    historical_raw = test[smoke_manifest["historical_raw_column_for_residual"]].to_numpy(np.longdouble)
    historical_delta = historical_raw - base
    _, historical_bias_pair = smoke.query_means(queries, historical_delta, unique_queries)
    residual = historical_delta - historical_bias_pair
    residual_means, _ = smoke.query_means(queries, residual, unique_queries)

    q_raw_values: list[np.longdouble] = []
    for query in unique_queries:
        current_labels = labels[queries == query]
        positives = int(current_labels.sum())
        negatives = int(len(current_labels) - positives)
        q_raw_values.append(
            np.log(
                (np.longdouble(positives) + np.longdouble(0.5))
                / (np.longdouble(negatives) + np.longdouble(0.5))
            )
        )
    q_raw = np.asarray(q_raw_values, dtype=np.longdouble)
    q_raw_variance = np.var(q_raw, ddof=0)
    if q_raw_variance <= np.longdouble(degenerate_threshold):
        raise RuntimeError(f"INFORMATIVE_COMPONENT_DEGENERATE: variance={float(q_raw_variance):.17g}")
    q = smoke.standardize_population(q_raw, degenerate_threshold, "INFORMATIVE_COMPONENT")
    q_lookup = dict(zip(unique_queries, q))
    q_pair = np.fromiter((q_lookup[query] for query in queries), dtype=np.longdouble, count=len(queries))

    frozen_query_components = pd.read_csv(
        formal_manifest["source_freeze"]["smoke_query_components"]["path"]
    ).sort_values("query", kind="mergesort")
    if list(frozen_query_components["query"].astype(str)) != list(unique_queries):
        raise RuntimeError("FROZEN_Q_QUERY_ALIGNMENT_FAIL")
    q_smoke_max_abs_difference = float(
        np.max(np.abs(q - frozen_query_components["q_i"].to_numpy(np.longdouble)))
    )
    if q_smoke_max_abs_difference > tolerance:
        raise RuntimeError("FROZEN_Q_VALUE_MISMATCH")

    q_mean = float(np.mean(q, dtype=np.longdouble))
    q_variance = float(np.var(q, ddof=0))
    max_residual_mean = float(np.max(np.abs(residual_means)))
    base_metrics = smoke.metric_bundle(queries, labels, base)

    condition_rows: list[dict[str, Any]] = []
    label_rows: list[dict[str, Any]] = []
    seed_qc_rows: list[dict[str, Any]] = []
    nuisance_rows: list[dict[str, Any]] = []

    for synthetic_seed in seeds:
        rng_seed = 10000 + synthetic_seed
        rng = np.random.default_rng(rng_seed)
        c_initial = smoke.standardize_population(
            rng.normal(0.0, 1.0, len(unique_queries)), degenerate_threshold, "NUISANCE_INITIAL"
        )
        projection_coefficient = np.sum(c_initial * q, dtype=np.longdouble) / np.sum(
            q * q, dtype=np.longdouble
        )
        c_projected = c_initial - projection_coefficient * q
        c = smoke.standardize_population(c_projected, degenerate_threshold, "NUISANCE_POST_PROJECTION")
        corr_q_c = np.sum(q * c, dtype=np.longdouble) / np.sqrt(
            np.sum(q * q, dtype=np.longdouble) * np.sum(c * c, dtype=np.longdouble)
        )
        c_lookup = dict(zip(unique_queries, c))
        c_pair = np.fromiter((c_lookup[query] for query in queries), dtype=np.longdouble, count=len(queries))
        c_mean = float(np.mean(c, dtype=np.longdouble))
        c_variance = float(np.var(c, ddof=0))
        nuisance_rows.append(
            {
                "seed": synthetic_seed,
                "rng_seed": rng_seed,
                "projection_coefficient": float(projection_coefficient),
                "c_mean": c_mean,
                "c_population_variance": c_variance,
                "corr_q_c": float(corr_q_c),
                "c_min": float(np.min(c)),
                "c_max": float(np.max(c)),
            }
        )

        seed_condition_start = len(condition_rows)
        for beta in betas:
            for gamma in gammas:
                beta_ld = np.longdouble(beta)
                gamma_ld = np.longdouble(gamma)
                target = base + residual + gamma_ld * q_pair
                raw = target + beta_ld * c_pair
                delta = raw - base
                b_hat_query, b_hat_pair = smoke.query_means(queries, delta, unique_queries)
                qrc = raw - b_hat_pair
                oracle_n = raw - beta_ld * c_pair
                true_observable_query = gamma_ld * q + beta_ld * c

                raw_error = smoke.score_errors(raw, target)
                qrc_error = smoke.score_errors(qrc, target)
                oracle_error = smoke.score_errors(oracle_n, target)
                bias_error = smoke.score_errors(b_hat_query, true_observable_query)
                informative_error = smoke.score_errors(qrc - target, -gamma_ld * q_pair)
                invariance = smoke.ranking_invariance(queries, raw, qrc)

                method_scores = {
                    "Base": base,
                    "Target": target,
                    "Raw": raw,
                    "QRC": qrc,
                    "OracleN": oracle_n,
                }
                current_metrics: dict[str, dict[str, float | int]] = {}
                for method, method_score in method_scores.items():
                    metrics = base_metrics if method == "Base" else smoke.metric_bundle(queries, labels, method_score)
                    current_metrics[method] = metrics
                    label_rows.append(
                        {
                            "seed": synthetic_seed,
                            "alpha": 1.0,
                            "beta": beta,
                            "gamma": gamma,
                            "method": method,
                            **metrics,
                            "role": "controlled_oracle_reference"
                            if method in {"Target", "OracleN"}
                            else "deployment_method",
                        }
                    )

                macro_difference = max(
                    abs(float(current_metrics["Raw"]["macro_auroc"]) - float(current_metrics["QRC"]["macro_auroc"])),
                    abs(float(current_metrics["Raw"]["macro_aupr"]) - float(current_metrics["QRC"]["macro_aupr"])),
                )
                if beta > gamma:
                    phase_region = "BETA_GT_GAMMA_QRC_EXPECTED_BETTER"
                    phase_pass = qrc_error["rmse"] < raw_error["rmse"]
                elif beta < gamma:
                    phase_region = "BETA_LT_GAMMA_RAW_EXPECTED_BETTER"
                    phase_pass = raw_error["rmse"] < qrc_error["rmse"]
                else:
                    phase_region = "BETA_EQ_GAMMA_EQUAL_EXPECTED"
                    phase_pass = abs(raw_error["rmse"] - qrc_error["rmse"]) <= tolerance

                raw_theory_error = raw_error["rmse"] - beta
                qrc_theory_error = qrc_error["rmse"] - gamma
                algebraic_pass = (
                    oracle_error["max_abs_error"] <= tolerance
                    and bias_error["max_abs_error"] <= tolerance
                    and informative_error["max_abs_error"] <= tolerance
                )
                invariance_pass = (
                    macro_difference <= macro_tolerance
                    and invariance["strict_order_violations"] == 0
                    and invariance["tie_violations"] == 0
                )
                theory_error_pass = (
                    abs(raw_theory_error) <= tolerance and abs(qrc_theory_error) <= tolerance
                )
                condition_valid = algebraic_pass and invariance_pass and theory_error_pass and phase_pass

                row: dict[str, Any] = {
                    "seed": synthetic_seed,
                    "rng_seed": rng_seed,
                    "alpha": 1.0,
                    "beta": beta,
                    "gamma": gamma,
                    "raw_to_target_mae": raw_error["mae"],
                    "raw_to_target_rmse": raw_error["rmse"],
                    "raw_to_target_max_abs_error": raw_error["max_abs_error"],
                    "qrc_to_target_mae": qrc_error["mae"],
                    "qrc_to_target_rmse": qrc_error["rmse"],
                    "qrc_to_target_max_abs_error": qrc_error["max_abs_error"],
                    "oracle_n_to_target_mae": oracle_error["mae"],
                    "oracle_n_to_target_rmse": oracle_error["rmse"],
                    "oracle_n_to_target_max_abs_error": oracle_error["max_abs_error"],
                    "bias_recovery_mae": bias_error["mae"],
                    "bias_recovery_rmse": bias_error["rmse"],
                    "bias_recovery_max_abs_error": bias_error["max_abs_error"],
                    "informative_removal_identity_mae": informative_error["mae"],
                    "informative_removal_identity_rmse": informative_error["rmse"],
                    "informative_removal_identity_max_abs_error": informative_error["max_abs_error"],
                    "strict_order_violations": invariance["strict_order_violations"],
                    "tie_violations": invariance["tie_violations"],
                    "max_pairwise_difference_error": invariance["max_pairwise_difference_error"],
                    "raw_qrc_macro_metric_difference": macro_difference,
                    "expected_raw_rmse": beta,
                    "raw_rmse_theory_error": raw_theory_error,
                    "expected_qrc_rmse": gamma,
                    "qrc_rmse_theory_error": qrc_theory_error,
                    "phase_region": phase_region,
                    "phase_boundary_status": "PASS" if phase_pass else "FAIL",
                    "algebraic_qc_status": "PASS" if algebraic_pass else "FAIL",
                    "ranking_invariance_status": "PASS" if invariance_pass else "FAIL",
                    "theory_error_status": "PASS" if theory_error_pass else "FAIL",
                    "condition_status": "VALID" if condition_valid else "CONTROLLED_QC_FAIL",
                    "qrc_uses_labels": False,
                    "test_derived_tuning": False,
                }
                for method, metrics in current_metrics.items():
                    prefix = method.lower()
                    for metric_name in ("pooled_auroc", "pooled_aupr", "macro_auroc", "macro_aupr"):
                        row[f"{prefix}_{metric_name}"] = float(metrics[metric_name])
                condition_rows.append(row)

        seed_conditions = pd.DataFrame(condition_rows[seed_condition_start:])
        component_checks = {
            "q_mean": abs(q_mean) <= tolerance,
            "q_variance": abs(q_variance - 1.0) <= tolerance,
            "c_mean": abs(c_mean) <= tolerance,
            "c_variance": abs(c_variance - 1.0) <= tolerance,
            "q_c_correlation": abs(float(corr_q_c)) <= tolerance,
            "residual_centering": max_residual_mean <= tolerance,
            "oracle_recovery": float(seed_conditions["oracle_n_to_target_max_abs_error"].max()) <= tolerance,
            "bias_recovery": float(seed_conditions["bias_recovery_max_abs_error"].max()) <= tolerance,
            "informative_removal_identity": float(
                seed_conditions["informative_removal_identity_max_abs_error"].max()
            )
            <= tolerance,
            "macro_invariance": float(seed_conditions["raw_qrc_macro_metric_difference"].max()) <= macro_tolerance,
            "strict_order": int(seed_conditions["strict_order_violations"].sum()) == 0,
            "tie_invariance": int(seed_conditions["tie_violations"].sum()) == 0,
            "qrc_uses_no_labels": True,
            "no_test_derived_tuning": True,
        }
        seed_status = "PASS" if all(component_checks.values()) and (seed_conditions["condition_status"] == "VALID").all() else "CONTROLLED_QC_FAIL"
        seed_qc_rows.append(
            {
                "seed": synthetic_seed,
                "rng_seed": rng_seed,
                "status": seed_status,
                "conditions": len(seed_conditions),
                "valid_conditions": int((seed_conditions["condition_status"] == "VALID").sum()),
                "phase_pass_conditions": int((seed_conditions["phase_boundary_status"] == "PASS").sum()),
                "phase_fail_conditions": int((seed_conditions["phase_boundary_status"] == "FAIL").sum()),
                "q_mean": q_mean,
                "q_population_variance": q_variance,
                "c_mean": c_mean,
                "c_population_variance": c_variance,
                "corr_q_c": float(corr_q_c),
                "max_abs_residual_query_mean": max_residual_mean,
                "max_oracle_n_to_target_error": float(seed_conditions["oracle_n_to_target_max_abs_error"].max()),
                "max_bias_recovery_error": float(seed_conditions["bias_recovery_max_abs_error"].max()),
                "max_informative_removal_identity_error": float(
                    seed_conditions["informative_removal_identity_max_abs_error"].max()
                ),
                "max_raw_qrc_macro_metric_difference": float(
                    seed_conditions["raw_qrc_macro_metric_difference"].max()
                ),
                "strict_order_violations_total": int(seed_conditions["strict_order_violations"].sum()),
                "tie_violations_total": int(seed_conditions["tie_violations"].sum()),
                "max_pairwise_difference_error": float(seed_conditions["max_pairwise_difference_error"].max()),
                "qrc_uses_labels": False,
                "test_derived_tuning": False,
                **{f"check_{name}": passed for name, passed in component_checks.items()},
            }
        )
        print(f"seed={synthetic_seed:02d} status={seed_status} valid={int((seed_conditions['condition_status'] == 'VALID').sum())}/25", flush=True)

    conditions = pd.DataFrame(condition_rows).sort_values(["seed", "beta", "gamma"]).reset_index(drop=True)
    labels_long = pd.DataFrame(label_rows).sort_values(["seed", "beta", "gamma", "method"]).reset_index(drop=True)
    seed_qc = pd.DataFrame(seed_qc_rows).sort_values("seed").reset_index(drop=True)
    nuisance = pd.DataFrame(nuisance_rows).sort_values("seed").reset_index(drop=True)

    if len(conditions) != 625 or conditions[["seed", "beta", "gamma"]].duplicated().any():
        raise RuntimeError("FORMAL_CONDITION_CARDINALITY_FAIL")
    if len(labels_long) != 3125 or labels_long[["seed", "beta", "gamma", "method"]].duplicated().any():
        raise RuntimeError("FORMAL_LABEL_METRIC_CARDINALITY_FAIL")

    recovery_columns = [
        "raw_to_target_mae",
        "raw_to_target_rmse",
        "raw_to_target_max_abs_error",
        "qrc_to_target_mae",
        "qrc_to_target_rmse",
        "qrc_to_target_max_abs_error",
        "oracle_n_to_target_mae",
        "oracle_n_to_target_rmse",
        "oracle_n_to_target_max_abs_error",
        "bias_recovery_mae",
        "bias_recovery_rmse",
        "bias_recovery_max_abs_error",
        "informative_removal_identity_mae",
        "informative_removal_identity_rmse",
        "informative_removal_identity_max_abs_error",
        "raw_rmse_theory_error",
        "qrc_rmse_theory_error",
    ]
    recovery_aggregate = mean_std_aggregate(conditions, ["beta", "gamma"], recovery_columns)
    label_aggregate = mean_std_aggregate(
        labels_long,
        ["beta", "gamma", "method"],
        ["pooled_auroc", "pooled_aupr", "macro_auroc", "macro_aupr"],
    )

    phase_by_seed = (
        conditions.groupby(["seed", "phase_region"], sort=True)["phase_boundary_status"]
        .agg(conditions="size", passed_conditions=lambda values: int((values == "PASS").sum()))
        .reset_index()
    )
    phase_by_seed["failed_conditions"] = phase_by_seed["conditions"] - phase_by_seed["passed_conditions"]
    phase_by_seed.insert(0, "scope", "seed")
    phase_overall = (
        conditions.groupby("phase_region", sort=True)["phase_boundary_status"]
        .agg(conditions="size", passed_conditions=lambda values: int((values == "PASS").sum()))
        .reset_index()
    )
    phase_overall["failed_conditions"] = phase_overall["conditions"] - phase_overall["passed_conditions"]
    phase_overall.insert(0, "scope", "overall")
    phase_overall.insert(1, "seed", "ALL")
    phase_summary = pd.concat([phase_overall, phase_by_seed], ignore_index=True)

    mean_condition_metrics = conditions.groupby(["beta", "gamma"], sort=True).mean(numeric_only=True).reset_index()
    OUTPUT.mkdir(parents=True, exist_ok=True)
    conditions.to_csv(OUTPUT / "ALL_CONDITIONS_PER_SEED.csv", index=False, float_format="%.17g")
    recovery_aggregate.to_csv(OUTPUT / "GROUND_TRUTH_RECOVERY_AGGREGATE.csv", index=False, float_format="%.17g")
    label_aggregate.to_csv(OUTPUT / "LABEL_METRICS_AGGREGATE.csv", index=False, float_format="%.17g")
    phase_summary.to_csv(OUTPUT / "PHASE_BOUNDARY_SUMMARY.csv", index=False, float_format="%.17g")
    seed_qc.to_csv(OUTPUT / "SEED_QC_SUMMARY.csv", index=False, float_format="%.17g")
    nuisance.to_csv(OUTPUT / "NUISANCE_COMPONENT_SUMMARY.csv", index=False, float_format="%.17g")
    heatmap(mean_condition_metrics, "raw_to_target_rmse", betas, gammas).to_csv(
        OUTPUT / "RAW_RMSE_HEATMAP.csv", index=False, float_format="%.17g"
    )
    heatmap(mean_condition_metrics, "qrc_to_target_rmse", betas, gammas).to_csv(
        OUTPUT / "QRC_RMSE_HEATMAP.csv", index=False, float_format="%.17g"
    )
    mean_condition_metrics["qrc_minus_raw_rmse"] = (
        mean_condition_metrics["qrc_to_target_rmse"] - mean_condition_metrics["raw_to_target_rmse"]
    )
    mean_condition_metrics["qrc_minus_raw_auroc"] = (
        mean_condition_metrics["qrc_pooled_auroc"] - mean_condition_metrics["raw_pooled_auroc"]
    )
    mean_condition_metrics["qrc_minus_raw_aupr"] = (
        mean_condition_metrics["qrc_pooled_aupr"] - mean_condition_metrics["raw_pooled_aupr"]
    )
